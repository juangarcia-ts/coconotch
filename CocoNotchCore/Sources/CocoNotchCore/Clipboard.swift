import Foundation

public struct ClipboardItem: Codable, Equatable, Identifiable, Sendable {
    public enum Kind: String, Codable, Sendable {
        case text
        case image
    }

    public var id: UUID
    public var kind: Kind
    /// The text, or for an image its file name, which is a hash of the image so copies of one image match.
    public var value: String
    public var isPinned: Bool

    public init(id: UUID = UUID(), kind: Kind, value: String, isPinned: Bool = false) {
        self.id = id
        self.kind = kind
        self.value = value
        self.isPinned = isPinned
    }
}

/// Types that password managers and other apps add to say a copy must not be kept (nspasteboard.org).
public let ignoredPasteboardTypes: Set<String> = [
    "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType",
]

/// What to record from a new clipboard: text wins over an image, since apps often add a picture of copied text.
public func getClipboardCaptureKind(
    types: [String], text: String?, sourceBundleID: String?, ignoredBundleIDs: Set<String>, capturesImages: Bool
) -> ClipboardItem.Kind? {
    guard ignoredPasteboardTypes.isDisjoint(with: types),
        !(sourceBundleID.map(ignoredBundleIDs.contains) ?? false)
    else { return nil }
    if let text, !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty { return .text }
    if capturesImages, types.contains("public.png") || types.contains("public.tiff") { return .image }
    return nil
}

/// Puts the item on top, moving it there if it was copied before (keeping its pin), and drops what no longer fits.
public func addClipboardItem(_ item: ClipboardItem, to history: [ClipboardItem], limit: Int) -> [ClipboardItem] {
    var item = item
    var rest = history
    if let index = rest.firstIndex(where: { $0.kind == item.kind && $0.value == item.value }) {
        item.id = rest[index].id
        item.isPinned = rest[index].isPinned
        rest.remove(at: index)
    }
    return trimClipboardHistory([item] + rest, limit: limit)
}

/// Drops the oldest unpinned items until the history fits the limit; pinned items always stay.
public func trimClipboardHistory(_ history: [ClipboardItem], limit: Int) -> [ClipboardItem] {
    var unpinnedRoom = limit - history.count(where: \.isPinned)
    return history.filter { item in
        if item.isPinned { return true }
        unpinnedRoom -= 1
        return unpinnedRoom >= 0
    }
}

/// Pinned items first, then the rest, newest first; a search matches text only.
public func getVisibleClipboardItems(_ history: [ClipboardItem], query: String) -> [ClipboardItem] {
    let query = query.trimmingCharacters(in: .whitespaces)
    let matches = history.filter { query.isEmpty || ($0.kind == .text && $0.value.localizedStandardContains(query)) }
    return matches.filter(\.isPinned) + matches.filter { !$0.isPinned }
}

/// Image files the old history used that the new one doesn't, to delete from disk.
public func getUnusedImageFiles(old: [ClipboardItem], new: [ClipboardItem]) -> Set<String> {
    let imageFiles = { (items: [ClipboardItem]) in Set(items.filter { $0.kind == .image }.map(\.value)) }
    return imageFiles(old).subtracting(imageFiles(new))
}

/// The text without blank lines or surrounding space, cut short so a long copy doesn't slow down layout.
public func formatClipboardPreview(_ text: String) -> String {
    let lines = text.split(whereSeparator: \.isNewline)
        .map { $0.trimmingCharacters(in: .whitespaces) }
        .filter { !$0.isEmpty }
    return String(lines.joined(separator: "\n").prefix(300))
}
